import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {createReviewTriage} from './review-triage.mjs';
import {createWorkBuddyQueue} from './workbuddy-queue.mjs';
import {activateRevision} from './revision-candidates.mjs';
import {renderedFixture,qualityFixture} from './processing-test-fixture.mjs';
import {testRef} from './route-test-fixture.mjs';

test('common HTTP revision returns a real processed PDF, preserves feedback and recovers exactly once',{skip:!process.env.WORKSPACE_TEST_PYTHON||!process.env.JFW_TEST_FONT_PROFILE},async t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'common-revision-http-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const rendered=renderedFixture(path.join(root,'render'),'raster-reletter');
 const old=path.join(root,'old.pdf');fs.writeFileSync(old,'%PDF-synthetic old output');
 const figure={id:'A-F1',articleId:'A',author:'fixture',number:'1',feedback:{revision:3,text:'replace label'},productionRoute:rendered.task.productionRoute,outputs:[{number:'1',file:{path:old}}],status:'异常'};
 const context={rows:[figure],metadata:{},pending:{},link:url=>({path:fileURLToPath(url)})};
 const refresh=()=>{figure.reviewVersion=createHash('sha256').update(JSON.stringify([figure.outputs.map(o=>[o.number,o.file.path,testRef(o.file.path).sha256]),figure.feedback.revision])).digest('hex');};refresh();
 const originalFeedback=JSON.stringify(figure.feedback),oldSha=testRef(old).sha256;
 let activations=0,acceptance=null;
 const queue=createWorkBuddyQueue({root:path.join(root,'queue'),publish:()=>{throw Error('No executor allowed');}});
 const options={root:path.join(root,'reviews'),origin:'http://local',token:'test-secret',queue,rows:context.rows,articles:[],refresh,
  activate:record=>{activations++;activateRevision(context,record);},qualityPython:process.env.WORKSPACE_TEST_PYTHON,getAcceptance:()=>acceptance};
 let service=createReviewTriage(options);
 const server=http.createServer((req,res)=>{if(!service.handle(req,res,new URL(req.url,'http://local')))res.writeHead(404).end();});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));t.after(()=>new Promise(resolve=>server.close(resolve)));
 const base='http://127.0.0.1:'+server.address().port;
 const post=async(endpoint,body,authorized=true)=>{const response=await fetch(base+endpoint,{method:'POST',headers:{'Content-Type':'application/json',Origin:'http://local',...(authorized?{Authorization:'Bearer test-secret'}:{})},body:JSON.stringify(body)});return {status:response.status,...await response.json()};};
 const submitted=await post('/revision-jobs/A-F1',{version:figure.reviewVersion});assert.equal(submitted.status,202);
 const id=submitted.job.id;
 const forbidden=await post('/review-triage/prepare-candidate',{id,productionRoute:figure.productionRoute},false);assert.equal(forbidden.status,403);
 const prepared=await post('/review-triage/prepare-candidate',{id,productionRoute:figure.productionRoute});assert.equal(prepared.status,202,JSON.stringify(prepared));
 const task=JSON.parse(fs.readFileSync(prepared.job.commonCandidate.task.path,'utf8'));
 const candidate=qualityFixture(task,rendered,root);
 const missing={...candidate};delete missing.processingEvidence;
 const rejected=await post('/review-triage/import-candidate',{id,candidate:missing});assert.equal(rejected.status,409);assert.equal(activations,0);assert.equal(figure.outputs[0].file.path,old);
 const returned=await post('/review-triage/import-candidate',{id,candidate});assert.equal(returned.status,202,JSON.stringify(returned));
 assert.equal(figure.status,'待终检');assert.equal(activations,1);assert.equal(queue.list().length,0);
 assert.equal(JSON.stringify(figure.feedback),originalFeedback);assert.equal(testRef(old).sha256,oldSha);assert.equal(figure.previousOutputs[0].file.path,old);
 assert.equal(returned.job.qualityVerification.manualStatus,'pending');assert.ok(fs.existsSync(returned.job.result.outputs[0].preview));
 const duplicate=await post('/review-triage/import-candidate',{id,candidate});assert.equal(duplicate.status,202);assert.equal(activations,1);
 acceptance={accepted:true,version:figure.reviewVersion};figure.status='终检通过';
 service=createReviewTriage(options);assert.equal(activations,1);assert.equal(figure.status,'终检通过');
 figure.outputs=[];delete figure.previousOutputs;figure.status='待制作';
 service=createReviewTriage(options);assert.equal(activations,2);assert.equal(service.list()[0].restoreError,undefined);assert.equal(figure.outputs[0].file.path,candidate.outputs[0].path);
 figure.feedback.text='new feedback at the same revision';
 const stale=await post('/review-triage/import-candidate',{id,candidate});assert.equal(stale.status,409);assert.equal(activations,2);
});
